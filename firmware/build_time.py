# Pre-build script for env:tarot. Writes the build machine's local wall-clock
# time into src/tarot/build_time.h on every build, so a freshly flashed board
# starts its clock from it. A plain __DATE__/__TIME__ would go stale whenever
# main.cpp itself did not need recompiling.
import calendar
import os
import time

Import("env")  # noqa: F821 (provided by PlatformIO)

# Local time expressed as if it were UTC: the firmware keeps no time zone, it
# just counts local seconds.
local_now = calendar.timegm(time.localtime())
path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "tarot", "build_time.h")  # noqa: F821
with open(path, "w") as f:
    f.write("// Generated by build_time.py on every build; do not edit.\n")
    f.write("#pragma once\n")
    f.write("#define BUILD_LOCAL_TIME %dLL  // %s\n" % (local_now, time.strftime("%Y-%m-%d %H:%M:%S")))
